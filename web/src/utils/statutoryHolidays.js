const iso = (d) => `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(d.getUTCDate()).padStart(2, '0')}`
function expand(start, end) {
  const [sy, sm, sd] = start.split('-').map(Number)
  const [ey, em, ed] = end.split('-').map(Number)
  const cur = new Date(Date.UTC(sy, sm - 1, sd))
  const last = new Date(Date.UTC(ey, em - 1, ed))
  const result = []
  while (cur <= last) {
    result.push(iso(cur))
    cur.setUTCDate(cur.getUTCDate() + 1)
  }
  return result
}

export function calendarData(year) {
  const y = Number(year)
  const ranges = HOLIDAY_RANGES[y] || []
  const names = {}
  const holidays = []
  for (const [start, end, name] of ranges) {
    holidays.push(...expand(start, end))
    if (name) names[start] = name
  }
  return {
    holidays: [...new Set(holidays)].sort(),
    workdays: [...new Set(MAKEUP_WORKDAYS[y] || [])].sort(),
    names,
  }
}

export const supportedYears = () => Object.keys(HOLIDAY_RANGES).map(Number).sort((a, b) => a - b)
